-- Additive: no debts/payments are inferred from sporting history.
CREATE TABLE finance_qrs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 pelada_id BIGINT NOT NULL REFERENCES peladas(id) ON DELETE CASCADE,
 file_key VARCHAR(100) NOT NULL, content_type VARCHAR(30) NOT NULL
);
CREATE INDEX ix_finance_qrs_pelada ON finance_qrs(pelada_id);
CREATE TABLE finance_accounts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 pelada_id BIGINT NOT NULL UNIQUE REFERENCES peladas(id) ON DELETE CASCADE,
 revision BIGINT NOT NULL DEFAULT 0,
 visibility VARCHAR(30) NOT NULL CHECK (visibility IN ('INDIVIDUAL','TRANSPARENT')),
 pix_key VARCHAR(200), pix_recipient VARCHAR(200), qr_id BIGINT REFERENCES finance_qrs(id)
);
CREATE INDEX ix_finance_accounts_qr ON finance_accounts(qr_id);
CREATE TABLE finance_managers (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 pelada_id BIGINT NOT NULL REFERENCES peladas(id) ON DELETE CASCADE,
 user_id BIGINT NOT NULL REFERENCES users(id),
 UNIQUE(pelada_id,user_id),
 FOREIGN KEY(pelada_id,user_id) REFERENCES pelada_members(pelada_id,user_id) ON DELETE CASCADE
);
CREATE INDEX ix_finance_managers_user ON finance_managers(user_id);
CREATE TABLE finance_people (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 pelada_id BIGINT NOT NULL REFERENCES peladas(id) ON DELETE CASCADE,
 user_id BIGINT REFERENCES users(id), name VARCHAR(200) NOT NULL,
 UNIQUE(pelada_id,user_id)
);
CREATE INDEX ix_finance_people_user ON finance_people(user_id);
CREATE TABLE finance_templates (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 pelada_id BIGINT NOT NULL REFERENCES peladas(id) ON DELETE CASCADE,
 name VARCHAR(200) NOT NULL, classification VARCHAR(30) NOT NULL CHECK (classification IN ('DAILY','MONTHLY','OTHER')),
 description VARCHAR(2000), pix_key VARCHAR(200), pix_recipient VARCHAR(200), qr_id BIGINT REFERENCES finance_qrs(id),
 archived BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX ix_finance_templates_pelada ON finance_templates(pelada_id);
CREATE INDEX ix_finance_templates_qr ON finance_templates(qr_id);
CREATE TABLE finance_lists (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 pelada_id BIGINT NOT NULL REFERENCES peladas(id) ON DELETE CASCADE,
 name VARCHAR(200) NOT NULL, classification VARCHAR(30) NOT NULL CHECK (classification IN ('DAILY','MONTHLY','OTHER')),
 status VARCHAR(30) NOT NULL CHECK (status IN ('DRAFT','OPEN','CLOSED','CANCELED')),
 description VARCHAR(2000), due_date DATE, daily_id BIGINT REFERENCES dailies(id) ON DELETE SET NULL,
 daily_label VARCHAR(200), pix_key VARCHAR(200), pix_recipient VARCHAR(200), qr_id BIGINT REFERENCES finance_qrs(id),
 published_at TIMESTAMPTZ, created_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX ix_finance_lists_pelada ON finance_lists(pelada_id,id DESC);
CREATE INDEX ix_finance_lists_daily ON finance_lists(daily_id);
CREATE INDEX ix_finance_lists_qr ON finance_lists(qr_id);
CREATE TABLE finance_charges (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 pelada_id BIGINT NOT NULL REFERENCES peladas(id) ON DELETE CASCADE,
 list_id BIGINT NOT NULL REFERENCES finance_lists(id) ON DELETE CASCADE,
 person_id BIGINT NOT NULL REFERENCES finance_people(id), user_id BIGINT REFERENCES users(id), person_name VARCHAR(200) NOT NULL,
 adjustment NUMERIC(14,2) NOT NULL, amount_due NUMERIC(14,2) NOT NULL CHECK (amount_due >= 0), due_date DATE,
 canceled BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE UNIQUE INDEX uq_finance_charge_person ON finance_charges(list_id,person_id) WHERE NOT canceled;
CREATE INDEX ix_finance_charges_pelada ON finance_charges(pelada_id);
CREATE INDEX ix_finance_charges_person ON finance_charges(person_id);
CREATE INDEX ix_finance_charges_user ON finance_charges(user_id);
CREATE TABLE finance_notices (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 pelada_id BIGINT NOT NULL REFERENCES peladas(id) ON DELETE CASCADE,
 charge_id BIGINT NOT NULL REFERENCES finance_charges(id) ON DELETE CASCADE,
 user_id BIGINT NOT NULL REFERENCES users(id), amount NUMERIC(14,2) NOT NULL CHECK (amount > 0),
 status VARCHAR(30) NOT NULL CHECK (status IN ('PENDING','CONFIRMED','REJECTED')),
 created_at TIMESTAMPTZ NOT NULL, resolved_at TIMESTAMPTZ, resolved_by BIGINT REFERENCES users(id), reason VARCHAR(1000),
 receipt_key VARCHAR(100), receipt_type VARCHAR(30), receipt_expires_at TIMESTAMPTZ, receipt_deleted_at TIMESTAMPTZ
);
CREATE UNIQUE INDEX uq_finance_notice_pending ON finance_notices(charge_id) WHERE status = 'PENDING';
CREATE INDEX ix_finance_notices_pelada ON finance_notices(pelada_id);
CREATE INDEX ix_finance_notices_charge ON finance_notices(charge_id,id DESC);
CREATE INDEX ix_finance_notices_user ON finance_notices(user_id);
CREATE INDEX ix_finance_notices_resolver ON finance_notices(resolved_by);
CREATE INDEX ix_finance_receipt_expiry ON finance_notices(receipt_expires_at) WHERE receipt_deleted_at IS NULL;
CREATE TABLE finance_movements (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 pelada_id BIGINT NOT NULL REFERENCES peladas(id) ON DELETE CASCADE,
 list_id BIGINT REFERENCES finance_lists(id), daily_id BIGINT REFERENCES dailies(id) ON DELETE SET NULL, daily_label VARCHAR(200),
 charge_id BIGINT REFERENCES finance_charges(id), notice_id BIGINT UNIQUE REFERENCES finance_notices(id),
 original_id BIGINT UNIQUE REFERENCES finance_movements(id),
 kind VARCHAR(30) NOT NULL CHECK (kind IN ('OPENING','RECEIPT','INCOME','EXPENSE','REFUND','REVERSAL')),
 amount NUMERIC(14,2) NOT NULL, obligation_delta NUMERIC(14,2) NOT NULL DEFAULT 0,
 effective_date DATE NOT NULL, method VARCHAR(30) NOT NULL CHECK (method IN ('PIX','CASH','TRANSFER','OTHER')),
 description VARCHAR(500) NOT NULL, category VARCHAR(100), created_by BIGINT NOT NULL REFERENCES users(id), created_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX ix_finance_movements_pelada ON finance_movements(pelada_id,id DESC);
CREATE INDEX ix_finance_movements_list ON finance_movements(list_id);
CREATE INDEX ix_finance_movements_daily ON finance_movements(daily_id);
CREATE INDEX ix_finance_movements_charge ON finance_movements(charge_id);
CREATE INDEX ix_finance_movements_actor ON finance_movements(created_by);
CREATE INDEX ix_finance_opening ON finance_movements(pelada_id) WHERE kind = 'OPENING';
CREATE TABLE finance_audit (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 pelada_id BIGINT NOT NULL REFERENCES peladas(id) ON DELETE CASCADE,
 actor_id BIGINT NOT NULL REFERENCES users(id), actor_name VARCHAR(200) NOT NULL,
 operation VARCHAR(100) NOT NULL CHECK (operation IN ('SETTINGS', 'MANAGERS', 'TEMPLATE', 'LIST_SAVE', 'PUBLISH', 'CLOSE', 'REOPEN', 'CANCEL', 'DUPLICATE', 'CHARGE_REPLACE', 'CHARGE_SAVE', 'PARTICIPANTS', 'CHARGE_CANCEL', 'RECEIVE', 'REPORT', 'CONFIRM', 'REJECT', 'CASH', 'REFUND', 'REVERSE', 'QR', 'MANAGERS_REVOKED', 'DAILY_DETACHED')), target VARCHAR(100) NOT NULL, reason VARCHAR(1000), created_at TIMESTAMPTZ NOT NULL,
 before_data TEXT, after_data TEXT, request_key UUID, request_hash VARCHAR(64), result_list_id BIGINT, UNIQUE(pelada_id,request_key)
);
CREATE INDEX ix_finance_audit_pelada ON finance_audit(pelada_id,id DESC);
CREATE INDEX ix_finance_audit_actor ON finance_audit(actor_id);
CREATE TABLE finance_template_components (
 owner_id BIGINT NOT NULL REFERENCES finance_templates(id) ON DELETE CASCADE,
 position INTEGER NOT NULL, name VARCHAR(100) NOT NULL, amount NUMERIC(14,2) NOT NULL CHECK (amount >= 0), PRIMARY KEY(owner_id,position)
);
CREATE TABLE finance_list_components (
 owner_id BIGINT NOT NULL REFERENCES finance_lists(id) ON DELETE CASCADE,
 position INTEGER NOT NULL, name VARCHAR(100) NOT NULL, amount NUMERIC(14,2) NOT NULL CHECK (amount >= 0), PRIMARY KEY(owner_id,position)
);
CREATE TABLE finance_charge_components (
 owner_id BIGINT NOT NULL REFERENCES finance_charges(id) ON DELETE CASCADE,
 position INTEGER NOT NULL, name VARCHAR(100) NOT NULL, amount NUMERIC(14,2) NOT NULL CHECK (amount >= 0), PRIMARY KEY(owner_id,position)
);
-- Preserve history even when a previous binary attempts its old deletion path.
CREATE FUNCTION protect_financial_pelada() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF EXISTS (SELECT 1 FROM finance_lists WHERE pelada_id = OLD.id AND published_at IS NOT NULL)
 OR EXISTS (SELECT 1 FROM finance_movements WHERE pelada_id = OLD.id) THEN
  RAISE EXCEPTION 'Pelada has financial history' USING ERRCODE = '23503';
 END IF;
 RETURN OLD;
END;
$$;
CREATE TRIGGER protect_financial_pelada BEFORE DELETE ON peladas FOR EACH ROW EXECUTE FUNCTION protect_financial_pelada();
